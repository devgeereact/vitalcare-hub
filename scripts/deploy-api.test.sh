#!/usr/bin/env bash
# Tests for scripts/deploy-api.sh using a local folder as the "server". Nothing remote is touched.
set -uo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
T="$ROOT/.local-test/tmp/deploy-api-test-$$"; mkdir -p "$T"; trap 'pkill -f "php -S 127.0.0.1:3198" 2>/dev/null; rm -rf "$T"' EXIT
H="$T/home"
PASS=0; FAILN=0
check() { if [ "$2" = "0" ]; then PASS=$((PASS+1)); else FAILN=$((FAILN+1)); echo "FAIL: $1"; fi; }
deploy() { bash "$ROOT/scripts/deploy-api.sh" local "$H" "$@" 2>&1; }

mkdir -p "$H/vitalcare-private/app" "$H/vitalcare-private/config" "$H/vitalcare-private/logs" "$H/vitalcare.uk/api/uploads"
echo "stray" > "$H/vitalcare.uk/api/uploads/keep.png"
echo "<?php return 'config';" > "$H/vitalcare-private/config/prod.php"; chmod 600 "$H/vitalcare-private/config/prod.php"
echo "SECRET-CONFIG-VALUE" > "$H/vitalcare-private/config/backup.cnf"

# dry run changes nothing: not files, and not folders either
BEFORE="$(cd "$H" && find . | sort | shasum -a 256)"
OUT="$(deploy)"; rc=$?
[ "$(cd "$H" && find . | sort | shasum -a 256)" = "$BEFORE" ]; check "dry run creates no files and no folders" $?
check "dry run exits 0" $rc
[ ! -e "$H/vitalcare-private/app/src/Api.php" ] && [ ! -e "$H/vitalcare.uk/api/index.php" ]; check "dry run writes nothing" $?
echo "$OUT" | grep -q "DRY RUN"; check "dry run says it is a dry run" $?
echo "$OUT" | grep -q "shim: would write"; check "dry run reports the shim it would write" $?

# real deploy
OUT="$(deploy --go)"; rc=$?
check "deploy exits 0" $rc
cmp -s backend/src/Api.php "$H/vitalcare-private/app/src/Api.php"; check "source files are copied exactly" $?
cmp -s backend/public/index.php "$H/vitalcare-private/app/public/index.php"; check "the front controller is copied" $?
[ -f "$H/vitalcare-private/app/migrations/001-users.sql" ] && [ -f "$H/vitalcare-private/app/bin/migrate.php" ] && [ -f "$H/vitalcare-private/app/bin/backup.sh" ]; check "migrations and CLI tools are copied" $?
[ ! -e "$H/vitalcare-private/app/tests" ] && [ -z "$(find "$H/vitalcare-private/app" -name '*.test.*')" ]; check "tests are not deployed" $?
grep -qF "Generated by scripts/deploy-api.sh" "$H/vitalcare.uk/api/index.php"; check "the shim carries the generated marker" $?
grep -q "VITALCARE_PRIVATE_ROOT=$H/vitalcare-private" "$H/vitalcare.uk/api/index.php"; check "the shim points at the private root" $?
! grep -qiE "password|passwd|token|api_key|SECRET-CONFIG-VALUE" "$H/vitalcare.uk/api/index.php"; check "the shim holds no credentials or config values" $?
php -l "$H/vitalcare.uk/api/index.php" >/dev/null; check "the shim is valid PHP" $?
[ "$(cat "$H/vitalcare.uk/api/uploads/keep.png")" = "stray" ]; check "an existing file in the docroot is left alone" $?
[ "$(cat "$H/vitalcare-private/config/backup.cnf")" = "SECRET-CONFIG-VALUE" ]; check "config files are never touched" $?
echo "$OUT" | grep -q "SECRET-CONFIG-VALUE"; [ $? -ne 0 ]; check "no config value appears in the output" $?
[ ! -e "$H/vitalcare.uk/.htaccess" ] && [ ! -e "$H/vitalcare.uk/index.html" ]; check ".htaccess and the static site are not touched" $?
[ ! -e "$H/vitalcare.uk/api/index.php.tmp" ] && [ ! -e "$H/vitalcare.uk/api/.htaccess.tmp" ]; check "no temporary file is left behind" $?
grep -q "AddHandler application/x-httpd-alt-php84___lsphp .php" "$H/vitalcare.uk/api/.htaccess"; check "api/.htaccess pins PHP 8.4 for the API folder" $?
grep -qF "Generated by scripts/deploy-api.sh" "$H/vitalcare.uk/api/.htaccess"; check "api/.htaccess carries the generated marker" $?
[ ! -e "$H/vitalcare.uk/.htaccess" ]; check "the docroot .htaccess is still not created or touched" $?

# idempotent
OUT2="$(deploy --go)"; rc=$?
check "a second deploy exits 0" $rc
echo "$OUT2" | grep -q "shim: unchanged"; check "a second deploy leaves the shim unchanged" $?
echo "$OUT2" | grep -q "api/.htaccess: unchanged"; check "a second deploy leaves api/.htaccess unchanged" $?
[ -z "$(echo "$OUT2" | grep -E '^[<>cd.][fdL]')" ]; check "a second deploy transfers no files" $?

# never deletes: a file that exists only on the server survives
echo "server-only" > "$H/vitalcare-private/app/src/ServerOnly.php"
deploy --go >/dev/null; [ -f "$H/vitalcare-private/app/src/ServerOnly.php" ]; check "files only present on the server are never deleted" $?

# refusals
echo "<?php // someone else's file" > "$H/vitalcare.uk/api/index.php"
deploy --go >/dev/null 2>&1; [ $? -ne 0 ]; check "refuses to overwrite an index.php this script did not write" $?
[ "$(cat "$H/vitalcare.uk/api/index.php")" = "<?php // someone else's file" ]; check "...and leaves it untouched" $?
rm "$H/vitalcare.uk/api/index.php"; deploy --go >/dev/null
echo "# someone else's rules" > "$H/vitalcare.uk/api/.htaccess"
deploy --go >/dev/null 2>&1; [ $? -ne 0 ]; check "refuses to overwrite an api/.htaccess this script did not write" $?
[ "$(cat "$H/vitalcare.uk/api/.htaccess")" = "# someone else's rules" ]; check "...and leaves it untouched" $?
rm "$H/vitalcare.uk/api/.htaccess"; API_PHP_HANDLER='x; rm -rf /' bash scripts/deploy-api.sh local "$H" --go >/dev/null 2>&1; [ $? -ne 0 ]; check "refuses an unsafe handler string" $?
deploy --go >/dev/null
mv "$H/vitalcare-private/config/prod.php" "$H/vitalcare-private/config/prod.php.gone"
deploy --go >/dev/null 2>&1; [ $? -ne 0 ]; check "refuses to deploy when the private config is missing" $?
mv "$H/vitalcare-private/config/prod.php.gone" "$H/vitalcare-private/config/prod.php"
bash scripts/deploy-api.sh local "relative/path" >/dev/null 2>&1; [ $? -ne 0 ]; check "refuses a relative home path" $?
bash scripts/deploy-api.sh local '/tmp/x; rm -rf /' >/dev/null 2>&1; [ $? -ne 0 ]; check "refuses an unsafe home path" $?
bash scripts/deploy-api.sh local "$H" --nope >/dev/null 2>&1; [ $? -ne 0 ]; check "refuses an unknown option" $?

# the deployed shim really serves the API (a router stands in for the .htaccess rule)
cat > "$T/router.php" <<'PHP'
<?php
$p = parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH);
if (preg_match('#^/api(/.*)?$#', $p) && $p !== '/api/index.php') { require $_SERVER['DOCUMENT_ROOT'] . '/api/index.php'; return true; }
return false;
PHP
(php -S 127.0.0.1:3198 -t "$H/vitalcare.uk" "$T/router.php" >/dev/null 2>&1 &); sleep 1
RESP="$(curl -s http://127.0.0.1:3198/api/health)"
echo "$RESP" | grep -q '"status":"ok"'; check "the deployed shim answers /api/health" $?
echo "$RESP" | grep -q '"authConfigured":false'; check "...and reports honestly that it is not configured (the test config is not a real one)" $?
[ "$(curl -s -o /dev/null -w '%{http_code}' http://127.0.0.1:3198/api/me)" = "503" ]; check "...and protected routes are 503, not open" $?
[ -s "$H/vitalcare-private/logs/php-error.log" ]; check "PHP errors went to the private log" $?
[ ! -e "$H/vitalcare.uk/api/error_log" ]; check "no error_log appears in the web root" $?

echo "deploy-api tests: $PASS passed, $FAILN failed"
[ "$FAILN" = "0" ]
