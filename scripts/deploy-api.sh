#!/usr/bin/env bash
# Deploy the PHP API to the hosting account. DRY RUN unless --go is given.
#
#   scripts/deploy-api.sh HOST REMOTE_HOME [--go]
#
#   HOST         ssh alias of the account, or "local" to deploy into a local folder (tests)
#   REMOTE_HOME  absolute home directory on the account, e.g. /home/ACCOUNT
#   DOCROOT      optional env: the web root; default REMOTE_HOME/vitalcare.uk
#
# What it does, and only this:
#  - copies backend/src, backend/bin, backend/migrations and backend/public/index.php into
#    REMOTE_HOME/vitalcare-private/app/ (outside every web root), by checksum, never deleting anything;
#  - writes the two-line shim DOCROOT/api/index.php (no secrets in it) that points at the private code.
# It refuses to run if the private config is missing, and refuses to overwrite a DOCROOT/api/index.php
# that this script did not write. It never touches config/, storage/, .htaccess or the static site.
set -euo pipefail

HOST="${1:-}"; RHOME="${2:-}"; MODE="${3:-}"
[ -n "$HOST" ] && [ -n "$RHOME" ] || { echo "usage: scripts/deploy-api.sh HOST REMOTE_HOME [--go]" >&2; exit 64; }
[ -z "$MODE" ] || [ "$MODE" = "--go" ] || { echo "the only option is --go" >&2; exit 64; }
case "$RHOME" in /*) ;; *) echo "REMOTE_HOME must be an absolute path" >&2; exit 64;; esac
case "$RHOME" in *[!A-Za-z0-9_/.-]*) echo "REMOTE_HOME contains unsafe characters" >&2; exit 64;; esac

cd "$(dirname "$0")/.."
APP="$RHOME/vitalcare-private/app"
DOCROOT="${DOCROOT:-$RHOME/vitalcare.uk}"
SHIM="$DOCROOT/api/index.php"
MARK="// Generated by scripts/deploy-api.sh. Contains no secrets; the code lives outside the web root."

if [ "$HOST" = "local" ]; then
  run() { bash -c "$1"; }
  DEST() { printf '%s' "$1"; }
else
  run() { ssh -o BatchMode=yes "$HOST" "$1"; }
  DEST() { printf '%s:%s' "$HOST" "$1"; }
fi

fail() { echo "FAIL: $*" >&2; exit 1; }

run "test -f '$RHOME/vitalcare-private/config/prod.php'" || fail "private config is missing: run the database step first"
run "test -d '$APP'" || fail "private app folder is missing"

SHIM_CONTENT="<?php
declare(strict_types=1);
$MARK
putenv('VITALCARE_PRIVATE_ROOT=$RHOME/vitalcare-private');
require '$APP/public/index.php';
"

RS=(rsync -rlt --checksum --itemize-changes --exclude '*.test.*' --exclude 'tests/')
[ "$MODE" = "--go" ] || RS+=(--dry-run)
[ "$MODE" = "--go" ] && echo "== DEPLOY to $HOST:$APP" || echo "== DRY RUN (checksum). Nothing is changed. Target: $HOST:$APP"

run "mkdir -p '$APP/src' '$APP/bin' '$APP/migrations' '$APP/public'" >/dev/null 2>&1 || true
[ "$MODE" = "--go" ] || true
for pair in "backend/src/:$APP/src/" "backend/bin/:$APP/bin/" "backend/migrations/:$APP/migrations/"; do
  "${RS[@]}" "${pair%%:*}" "$(DEST "${pair#*:}")"
done
"${RS[@]}" backend/public/index.php "$(DEST "$APP/public/index.php")"

# The shim: only ever replace one this script wrote.
CURRENT="$(run "cat '$SHIM' 2>/dev/null" || true)"
if [ -n "$CURRENT" ] && ! printf '%s' "$CURRENT" | grep -qF "$MARK"; then
  fail "$SHIM exists and was not written by this script; refusing to overwrite it"
fi
if [ "$CURRENT" = "${SHIM_CONTENT%$'\n'}" ] || [ "$CURRENT" = "$SHIM_CONTENT" ]; then
  echo "shim: unchanged"
elif [ "$MODE" = "--go" ]; then
  run "mkdir -p '$DOCROOT/api'"
  printf '%s' "$SHIM_CONTENT" | run "cat > '$SHIM.tmp' && mv '$SHIM.tmp' '$SHIM'"
  echo "shim: written to $SHIM"
else
  echo "shim: would write $SHIM"
fi
[ "$MODE" = "--go" ] && echo "== done" || echo "== DRY RUN done. Re-run with --go once approved."
