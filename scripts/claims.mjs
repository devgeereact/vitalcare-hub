#!/usr/bin/env node
// Turns docs/claims.yml into src/generated/claims.ts. Only PROVEN claims are exported, so using a
// claim that is still REQUIRED is a compile-time error (see src/content/claims.ts).
//   node scripts/claims.mjs           write the file
//   node scripts/claims.mjs --check   fail if the file is missing or stale (used by pnpm check)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "docs/claims.yml");
const target = resolve(root, "src/generated/claims.ts");
const check = process.argv.includes("--check");

const doc = parse(readFileSync(source, "utf8"));
const problems = [];
const proven = {};
const required = [];

for (const [key, value] of Object.entries(doc ?? {})) {
  if (!/^[a-z][a-z0-9_]*$/.test(key)) problems.push(`${key}: key must be snake_case`);
  const status = value?.status;
  if (status === "PROVEN") {
    for (const f of ["text", "evidence", "owner"]) {
      if (typeof value[f] !== "string" || value[f].trim() === "")
        problems.push(`${key}: PROVEN needs ${f}`);
    }
    proven[key] = String(value.text ?? "");
  } else if (status === "REQUIRED") {
    if (typeof value.needs !== "string" || value.needs.trim() === "")
      problems.push(`${key}: REQUIRED needs a "needs" description`);
    if ((value.text ?? "") !== "")
      problems.push(`${key}: REQUIRED must have empty text (nothing ships until proven)`);
    required.push(key);
  } else {
    problems.push(`${key}: status must be PROVEN or REQUIRED`);
  }
}

if (problems.length) {
  console.error("claims.yml is invalid:\n- " + problems.join("\n- "));
  process.exit(1);
}

const lines = [
  "// Generated by scripts/claims.mjs from docs/claims.yml. Do not edit by hand.",
  "// Only PROVEN claims appear here. A REQUIRED claim cannot be used: it is not a valid ClaimKey.",
  "export const CLAIMS = {",
  ...Object.entries(proven).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
  "} as const;",
  "",
  "export type ClaimKey = keyof typeof CLAIMS;",
  "",
  `/** Claims still waiting for proof. Listed for reference only; the app cannot use them. */`,
  `export const REQUIRED_CLAIMS: readonly string[] = ${JSON.stringify(required)};`,
  "",
];
const output = lines.join("\n");

if (check) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== output) {
    console.error("src/generated/claims.ts is stale. Run: node scripts/claims.mjs");
    process.exit(1);
  }
  console.log(`claims ok: ${Object.keys(proven).length} proven, ${required.length} required`);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
  console.log(
    `wrote ${target} (${Object.keys(proven).length} proven, ${required.length} required)`,
  );
}
